// Matchers intégrés de Jasmine :
/*
    toBe() Identité stricte (===)
    toEqual() Égalité profonde (objets, tableaux)
    toBeTruthy() / toBeFalsy() Valeur vraie/fausse
    toContain() Contient un élément (tableau ou chaîne)
    toThrow() / toThrowError() Exception lancée
    toBeDefined() / toBeUndefined() Vérifie si défini
    toBeNull() Valeur null
    toMatch() Expression régulière
*/